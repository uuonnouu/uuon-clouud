router.get('/term/:termId', (req: Request, res: Response) => {
  const { termId } = req.params;
  const entry = LEXICON_DATABASE[termId];
  
  if (!entry) {
    return res.status(404).json({ success: false, error: 'Term not found' });
  }
  
  res.json({ success: true, entry });
});

router.get('/search', (req: Request, res: Response) => {
  const { q, category, lang } = req.query;
  const query = (q as string || '').toLowerCase();
  
  let results = Object.values(LEXICON_DATABASE);
  
  if (query) {
    results = results.filter(entry =>
      entry.term.toLowerCase().includes(query) ||
      entry.definition.toLowerCase().includes(query) ||
      entry.synonyms.some(s => s.toLowerCase().includes(query))
    );
  }
  
  if (category) {
    results = results.filter(entry => entry.category === category);
  }
  
  res.json({ success: true, count: results.length, results });
});

router.get('/formula/:formulaId', (req: Request, res: Response) => {
  const { formulaId } = req.params;
  const { lang } = req.query;
  const formula = FORMULA_DATABASE[formulaId];
  
  if (!formula) {
    return res.status(404).json({ success: false, error: 'Formula not found' });
  }
  
  if (lang && formula.implementations[lang as keyof typeof formula.implementations]) {
    return res.json({
      success: true,
      formula: {
        ...formula,
        selectedImplementation: formula.implementations[lang as keyof typeof formula.implementations]
      }
    });
  }
  
  res.json({ success: true, formula });
});

