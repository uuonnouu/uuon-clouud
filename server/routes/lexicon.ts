router.get('/related/:termId', (req: Request, res: Response) => {
  const { termId } = req.params;
  const entry = LEXICON_DATABASE[termId];
  
  if (!entry) {
    return res.status(404).json({ success: false, error: 'Term not found' });
  }
  
  const related = Object.values(LEXICON_DATABASE)
    .filter(e => e.id !== termId && e.category === entry.category)
    .slice(0, 5);
  
  res.json({ success: true, term: termId, related });
});

