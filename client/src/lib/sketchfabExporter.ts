export type SketchfabTransparencyMode = 'opaque' | 'alpha_mask' | 'blending' | 'dithered' | 'additive' | 'refraction';

export interface SketchfabMaterialSettings {
  transparencyMode: SketchfabTransparencyMode;
  alphaThreshold: number;
  invertAlpha: boolean;
  tintColor: THREE.Color;
  indexOfRefraction: number;
  refractionRoughness: number;
  useNormalOffset: boolean;
}

export interface SketchfabExportOptions {
  filename: string;
  textureResolution: 1024 | 2048 | 4096 | 8192;
  uvMappingMode: UVMappingMode;
  uvScale: number;
  materialSettings: Partial<SketchfabMaterialSettings>;
  bakeLighting: boolean;
  exportSeparateTextures: boolean;
  includeAnimation: boolean;
  animationDuration: number;
  quality: 'standard' | 'high' | 'ultra';
  attribution: boolean;
}

export interface TextureExportResult {
  name: string;
  dataUrl: string;
  width: number;
  height: number;
  type: 'albedo' | 'normal' | 'roughness' | 'metallic' | 'ao' | 'opacity';
}

export interface SketchfabExportResult {
  success: boolean;
  glbBlob?: Blob;
  textures?: TextureExportResult[];
  metadata: SketchfabMetadata;
  attribution: string;
  error?: string;
}

export interface SketchfabMetadata {
  name: string;
  category: string;
  vertexCount: number;
  faceCount: number;
  textureResolution: number;
  transparencyMode: SketchfabTransparencyMode;
  uvMappingMode: UVMappingMode;
  hasNormalMap: boolean;
  hasPBRMaterials: boolean;
  exportDate: string;
  generator: string;
}

