// Embed provenance into PNG as a tEXt chunk in the filename and as
// invisible pixels in the bottom-left 8×1 strip (LSB steganography).
function stampCanvasProvenance(canvas: HTMLCanvasElement, sessionHash: string): void {
  const ctx = canvas.getContext("2d");
  if (!ctx) return;
  // Write hash bits into bottom-left 64 pixels — imperceptible at any zoom
  const hashBits = sessionHash.split("").map(c => c.charCodeAt(0).toString(2).padStart(8, "0")).join("").slice(0, 64);
  const imageData = ctx.getImageData(0, canvas.height - 1, 64, 1);
  for (let i = 0; i < 64; i++) {
    // Flip LSB of blue channel: visible change is ±1 out of 255, invisible
    imageData.data[i * 4 + 2] = (imageData.data[i * 4 + 2] & 0xFE) | parseInt(hashBits[i] || "0");
  }
  ctx.putImageData(imageData, 0, canvas.height - 1);
}

// ─── Field Math ───────────────────────────────────────────────────────────────

function calcField(x: number, y: number, z: number, algo: string, p: any): number {
  const { frequency, amplitude, phase, time } = p;
  const k = Math.max(0.1, frequency * 2 * Math.PI);
  const w = frequency * time;
  x = Math.max(-10, Math.min(10, x || 0));
  y = Math.max(-10, Math.min(10, y || 0));
  z = Math.max(-10, Math.min(10, z || 0));
  let r = 0;
  switch (algo) {
    case "EM_PLANE": { const rad = Math.sqrt(x*x+y*y+z*z); r = amplitude * Math.sin(k*rad - w + phase); break; }
    case "TEM":      { const e = Math.max(-50, -(x*x+y*y)/Math.max(0.1, 0.5+frequency*0.1)); r = amplitude * Math.exp(e) * Math.cos(k*z - w + phase); break; }
    case "TE":       { const f = Math.max(0.1, frequency); r = amplitude * Math.sin((Math.PI*x)/f) * Math.cos(k*z - w + phase); break; }
    case "TM":       { const rho = Math.sqrt(x*x+y*y), th = Math.atan2(y,x); r = amplitude * Math.sin(k*rho) * Math.cos(th - w + phase); break; }
    case "GAUSSIAN_BEAM": { const w0=Math.max(0.1,0.5+frequency*0.1), zR=Math.PI*w0*w0/Math.max(0.1,frequency), wz=w0*Math.sqrt(1+Math.pow(z/zR,2)); r = amplitude * Math.exp(Math.max(-50,-(x*x+y*y)/(wz*wz))) * Math.cos(k*z - w + phase); break; }
    case "HERMITE_GAUSS": { const wx=Math.max(0.1,0.3+frequency*0.05), wy=Math.max(0.1,0.4+frequency*0.05); r = amplitude * (2*x/wx) * (2*y/wy) * Math.exp(Math.max(-50,-(x*x/(wx*wx)+y*y/(wy*wy)))) * Math.cos(k*z - w + phase); break; }
    case "LAGUERRE_GAUSS": { const rho=Math.sqrt(x*x+y*y), phi=Math.atan2(y,x), wl=Math.max(0.1,0.4+frequency*0.1); r = amplitude * rho * Math.exp(Math.max(-50,-(rho*rho)/(wl*wl))) * Math.cos(2*phi + k*z - w + phase); break; }
    case "SPHERICAL_H":  { const rad=Math.max(0.001,Math.sqrt(x*x+y*y+z*z)), th=Math.acos(Math.max(-1,Math.min(1,z/rad))), phi=Math.atan2(y,x); r = amplitude * Math.sin(th)*Math.cos(2*phi) * Math.cos(k*rad - w + phase); break; }
    case "GLL": { const xi=Math.max(-1,Math.min(1,x)), eta=Math.max(-1,Math.min(1,y)); r = amplitude * (0.5*(3*xi*xi-1)) * (0.5*(3*eta*eta-1)) * Math.exp(-((xi*xi+eta*eta)*frequency)) * (1+Math.sin(time*5)); break; }
    case "GRL": { const u=Math.tanh(x*frequency), v=Math.tanh(y*frequency); r = amplitude * Math.pow(u*u+v*v,0.5) * Math.exp(-Math.abs(u*v)*frequency) * 0.5*(1+Math.sin(time*8+phase)); break; }
    case "GL":  { const rad=Math.sqrt(x*x+y*y); r = amplitude * Math.exp(-rad*frequency*0.5) * (1-rad*0.3) * (1 + 0.5*Math.sin(k*rad-w*2+phase)*Math.cos(time*3)); break; }
    case "MORTAR": { const fx=Math.floor(x*frequency*2)+Math.sin(x*frequency*5), fy=Math.floor(y*frequency*2)+Math.sin(y*frequency*5); r = amplitude * Math.abs(Math.sin(fx)*Math.cos(fy)) * Math.exp(-Math.abs(x*y)*frequency*0.3) * (0.7+0.3*Math.sin(time*6)); break; }
    case "HP_SEM":  { const s1=Math.sin(x*frequency)*Math.cos(y*frequency), s2=Math.sin(x*frequency*3)*Math.cos(y*frequency*3)*0.5, s3=Math.sin(x*frequency*9)*Math.cos(y*frequency*9)*0.25; r = amplitude * (s1+s2+s3) * Math.exp(-time*0.1) * (1+Math.sin(time*10)); break; }
    case "DG_SPECTRAL": { const cx=Math.floor(x*frequency*2), cy=Math.floor(y*frequency*2), cellE=(cx+cy)%2===0?1:-0.5, lx=x*frequency*2-cx, ly=y*frequency*2-cy; r = amplitude * cellE * (2*lx-1)*(2*ly-1) * Math.exp(-Math.sqrt(lx*lx+ly*ly)*frequency) * (0.8+0.2*Math.sin(time*7)); break; }
    default: r = 0;
  }
  if (!isFinite(r)) r = 0;
  return 2 * Math.tanh(r / 2);
}

function buildGeometry(shape: string, density: number): THREE.BufferGeometry {
  const seg = Math.max(8, Math.min(256, density));
  switch (shape) {
    case "sphere":   return new THREE.SphereGeometry(1, seg, seg);
    case "box":      return new THREE.BoxGeometry(1.4, 1.4, 1.4, seg, seg, seg);
    case "torus":    return new THREE.TorusGeometry(0.9, 0.4, Math.max(8, seg/2), seg);
    case "cylinder": return new THREE.CylinderGeometry(0.9, 0.9, 1.8, seg, Math.max(4, seg/2));
    default:         return new THREE.PlaneGeometry(2, 2, seg, seg);
  }
}

function applyDisplacement(geometry: THREE.BufferGeometry, algo: string, params: any): void {
  geometry.computeVertexNormals();
  const pos  = geometry.attributes.position as THREE.BufferAttribute;
  const norm = geometry.attributes.normal   as THREE.BufferAttribute;
  const base = (geometry.userData.basePositions as Float32Array) || (pos.array as Float32Array).slice();
  geometry.userData.basePositions = base;
  for (let i = 0; i < pos.count; i++) {
    const ix = i * 3;
    const bx = base[ix], by = base[ix+1], bz = base[ix+2];
    const h  = calcField(bx, by, bz, algo, params) * params.displacement;
    pos.array[ix]   = bx + norm.array[ix]   * h;
    pos.array[ix+1] = by + norm.array[ix+1] * h;
    pos.array[ix+2] = bz + norm.array[ix+2] * h;
  }
  (pos as any).needsUpdate = true;
  geometry.computeVertexNormals();
}

