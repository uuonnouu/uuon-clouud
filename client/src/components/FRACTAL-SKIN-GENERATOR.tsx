function generateSessionHash(): string {
  // Lightweight client-side provenance token (mirrors Ellomental structure)
  // Full Ellomental hash generated server-side on /api/ellomental/verify
  const timestamp = Date.now();
  const seed      = `UUON-FSG-${timestamp}-Phillip-Aguilar-Ruiz-III`;
  let   hash      = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = ((hash << 5) - hash) + seed.charCodeAt(i);
    hash |= 0;
  }
  return `UUON-${Math.abs(hash).toString(16).padStart(8, "0").toUpperCase()}-${timestamp.toString(36).toUpperCase()}`;
}

