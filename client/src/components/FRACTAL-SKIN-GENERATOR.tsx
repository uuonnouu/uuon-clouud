// ─── Sub-components ───────────────────────────────────────────────────────────

const sectionHead: React.CSSProperties = { color: "#00e5cc", fontSize: 13, letterSpacing: 1, marginBottom: 8, marginTop: 4 };

function btnStyle(active: boolean, sem: boolean): React.CSSProperties {
  return { background: active ? (sem ? "rgba(255,138,61,0.3)" : "rgba(0,229,204,0.3)") : "rgba(255,255,255,0.05)", border: `1px solid ${sem ? "#ff8a3d" : "#00e5cc"}`, color: sem ? "#ff8a3d" : "#00e5cc", borderRadius: 5, padding: "6px 6px", fontSize: 10, cursor: "pointer" };
}

function ColorRow({ label, value, onChange }: { label: string; value: string; onChange: (v: string) => void }) {
  return (
    <div style={{ display: "flex", alignItems: "center", marginBottom: 6, gap: 8 }}>
      <label style={{ minWidth: 80, fontSize: 11, color: "#ccc" }}>{label}</label>
      <input type="color" value={value} onChange={e => onChange(e.target.value)} style={{ width: 36, height: 22, border: "1px solid rgba(255,255,255,0.2)", borderRadius: 4, background: "none", padding: 0, cursor: "pointer" }} />
      <span style={{ fontSize: 10, color: "#9aa" }}>{value}</span>
    </div>
  );
}

function Slider({ label, min, max, step, value, onChange }: { label: string; min: number; max: number; step: number; value: number; onChange: (v: number) => void }) {
  return (
    <div style={{ display: "flex", alignItems: "center", marginBottom: 8, gap: 8 }}>
      <label style={{ minWidth: 90, fontSize: 11, color: "#ccc" }}>{label}</label>
      <input type="range" min={min} max={max} step={step} value={value} onChange={e => onChange(parseFloat(e.target.value))} style={{ flex: 1 }} />
      <span style={{ minWidth: 36, fontSize: 11, color: "#00e5cc", textAlign: "right" }}>{Math.round(value * 100) / 100}</span>
    </div>
  );
}
