              <button onClick={randomize} style={{ width: "100%", marginBottom: 8, padding: "8px", background: "linear-gradient(45deg,#7b5ea7,#00e5cc)", border: "none", color: "#04080f", fontWeight: "bold", borderRadius: 5, cursor: "pointer", fontSize: 12 }}>🎲 Randomize</button>

